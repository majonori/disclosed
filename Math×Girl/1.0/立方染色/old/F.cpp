#include<bits/stdc++.h>
inline int f(int x,int y,int z){
  return x*9+y*3+z;
}
int F[3][3][3];
int main(){
	std::ios::sync_with_stdio(0);
	std::cin.tie(0),std::cout.tie(0);
  for(int i=0,w;i!=154;i++){
		std::cin>>w;
    std::bitset<27>A(w);
		int x1=0,x2=0,y1=0,y2=0,z1=0,z2=0;
		for(int a=0;a!=3;a++){
			for(int b=0;b!=3;b++){
				x1+=A[f(0,a,b)],x2+=A[f(1,a,b)];
				y1+=A[f(a,0,b)],y2+=A[f(a,1,b)];
				z1+=A[f(a,b,0)],z2+=A[f(a,b,1)];
			}
		}
		int a=0,b=0,c=0;
		if(x1==0)a=2;if(x2==0)a=1;
		if(y1==0)b=2;if(y2==0)b=1;
		if(z1==0)c=2;if(z2==0)c=1;
		std::cout<<i+1<<":";
		for(int x=0;x!=8;x++){
			std::bitset<3>X(x);
			if(X[0]==1&&a==0)continue;
			if(X[1]==1&&b==0)continue;
			if(X[2]==1&&c==0)continue;
			F[X[0]*a][X[1]*b][X[2]*c]++;
			std::cout<<((X[0]*a!=0)+(X[1]*b!=0)+(X[2]*c!=0))%2<<",";
		}
		std::cout<<"\n";
  }
	for(int x=0;x!=3;x++){
		for(int y=0;y!=3;y++){
			for(int z=0;z!=3;z++)
				std::cout<<F[x][y][z]<<",";
			std::cout<<"-----";
		}
		std::cout<<"\n";
	}
  return 0;
}
